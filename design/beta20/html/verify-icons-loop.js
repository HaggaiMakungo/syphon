async(page)=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.emulateMedia({reducedMotion:'no-preference'});
 await page.setViewportSize({width:1100,height:1100});
 await page.goto('http://127.0.0.1:8767/icons.html');
 await page.waitForFunction(()=>document.querySelector('#hero-icon').shadowRoot?.querySelector('.charging'));
 const icon=page.locator('#hero-icon');
 const timing=await icon.evaluate(el=>{const a=el.shadowRoot.querySelector('.charging').getAnimations()[0];return {duration:a.effect.getTiming().duration,iterations:a.effect.getTiming().iterations===Infinity}});
 if(timing.duration!==1000||!timing.iterations)throw Error('Expected rapid infinite charging loop');
 await page.waitForFunction(()=>document.querySelector('#hero-icon').shadowRoot.querySelector('.charging').getAnimations()[0].currentTime>2100);
 if(await icon.evaluate(el=>el.progress)!==34)throw Error('Loop must be independent of actual progress');
 const moving=await icon.evaluate(async el=>{const part=el.shadowRoot.querySelector('.charging');const a=getComputedStyle(part).transform;await new Promise(r=>setTimeout(r,180));return a!==getComputedStyle(part).transform});
 if(!moving)throw Error('No visible fill motion');
 await page.getByRole('button',{name:'Pause',exact:true}).click();
 const frozen=await icon.evaluate(el=>getComputedStyle(el.shadowRoot.querySelector('.charging')).transform);
 await page.evaluate(()=>new Promise(r=>setTimeout(r,200)));
 if(await icon.evaluate(el=>getComputedStyle(el.shadowRoot.querySelector('.charging')).transform)!==frozen)throw Error('Paused loop moved');
 await page.getByRole('button',{name:'Resume',exact:true}).click();
 if(await icon.evaluate(el=>el.shadowRoot.querySelector('.charging').getAnimations()[0].playState)!=='running')throw Error('Loop did not resume');
 await icon.evaluate(el=>{window.iconCompletion={count:0,end:0};el.addEventListener('completion',()=>iconCompletion.count++);el.addEventListener('shimmerend',()=>iconCompletion.end++)});
 await page.getByRole('button',{name:'Complete',exact:true}).click();
 if(await icon.evaluate(el=>!!el.shadowRoot.querySelector('.charging')))throw Error('Loop continued after completion');
 await page.waitForFunction(()=>iconCompletion.end===1);
 if(await icon.evaluate(el=>!!el.shadowRoot.querySelector('.shimmer.run')))throw Error('Completion shimmer did not stop');
 await page.getByRole('button',{name:'Complete',exact:true}).click();
 if(await page.evaluate(()=>iconCompletion.count)!==1)throw Error('Repeated completion shimmer');
 await page.getByRole('button',{name:'Start loop',exact:true}).click();
 if(await icon.evaluate(el=>el.shadowRoot.querySelector('.charging').getAnimations()[0].playState)!=='running')throw Error('Could not restart activity');
 await page.emulateMedia({reducedMotion:'reduce'});
 const reduced=await icon.evaluate(el=>el.shadowRoot.querySelector('.charging').getAnimations().length);
 if(reduced!==0)throw Error('Reduced motion still loops');
 await page.getByRole('button',{name:'Complete',exact:true}).click();
 if(await icon.evaluate(el=>!!el.shadowRoot.querySelector('.shimmer.run')))throw Error('Reduced motion shimmer');
 await page.setViewportSize({width:360,height:800});
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Narrow overflow');
 await page.emulateMedia({reducedMotion:'no-preference'});await page.setViewportSize({width:1100,height:1100});
 await page.goto('http://127.0.0.1:8767/icons.html');
 if(errors.length)throw Error(errors.join('\n'));
 return {loopDurationMs:1000,repeating:true,independentOfPercentage:true,visibleFillMotion:true,pauseResume:true,completionStopsLoop:true,shimmerOnce:true,reducedMotion:true,errors};
}
